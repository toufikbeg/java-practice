public class SmallerLarger {
    public static void main(String[] args) {
        int a = 42;
        int b = 17;
        if (a > b) {
            System.out.println("Larger: " + a + ", Smaller: " + b);
        } else {
            System.out.println("Larger: " + b + ", Smaller: " + a);
        }
    }
}
